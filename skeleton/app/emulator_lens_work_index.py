"""Canonical emulator review catalogue to a closed, source-pinned work index.

Only the original lens registry and training report validator assign work.
No review outcome is generated by this module.
"""
from __future__ import annotations

from dataclasses import dataclass
from collections import Counter
from copy import deepcopy

from skeleton.app.recovered_evidence import (
    EvidenceError, canonical, digest, integer, pin, seal, text, HEX,
)
from skeleton.jeeves.game_emulator_lens_review import (
    review_verified_training_report,validate_training_receipts,
)
from skeleton.jeeves.game_emulator_lens_campaign import audit_lens_campaign

LANES=("jeeves_playback","dragon_observation","adversarial_review")
MAX_TASKS=12_288
PAGE_SIZE=128
MAX_SOURCE_BYTES=8*1024*1024


@dataclass(frozen=True)
class WorkIndex:
    source_digest: str
    catalog_digest: str
    campaign_audit_digest: str
    identity: str
    tasks: tuple

    @property
    def by_identity(self):
        return {task["task_id"]:task for task in self.tasks}


def load_index(source,*,expected_source_digest,authorized):
    if authorized is not True:
        raise PermissionError("explicit local lens review operator required")
    if type(source) is not dict or len(canonical(source))>MAX_SOURCE_BYTES:
        raise EvidenceError("invalid canonical source report")
    source=deepcopy(source)
    validated=validate_training_receipts(source)
    pin(validated["report_digest"],expected_source_digest)
    pages=[]
    cursor=0
    tasks=[]
    lens_count=None
    while True:
        if len(pages)>=128:
            raise EvidenceError("lens page ceiling")
        page=review_verified_training_report(source,offset=cursor,limit=PAGE_SIZE)
        if lens_count is None:
            lens_count=integer(page["catalog_lens_count"],1,MAX_TASKS//len(LANES))
        if page["offset"]!=cursor or not page["reviews"]:
            raise EvidenceError("canonical lens pagination diverged")
        pages.append(page)
        for record in page["reviews"]:
            required=integer(record["required_distinct_replayed_runs"],1,100_000)
            available=integer(record["available_replayed_runs"],1,100_000)
            receipts=list(record["source_receipt_digests"])
            if (available!=validated["run_count"] or len(receipts)!=min(required,available)
                    or len(set(receipts))!=len(receipts)
                    or not set(receipts)<=set(validated["receipt_digests"])
                    or record["review_material_ready"]!=(available>=required)):
                raise EvidenceError("lens material claim differs from canonical source")
            for lane in LANES:
                specification=record[lane]
                task={"source_report_digest":expected_source_digest,
                      "catalog_digest":page["catalog_digest"],"review_id":record["review_id"],
                      "lens_key":record["lens_key"],"family":record["family"],"lane":lane,
                      "required_runs":required,"available_runs":available,
                      "source_receipt_set_digest":digest(receipts),"source_receipt_digests":receipts,
                      "canonical_task_digest":digest(specification),
                      "canonical_task":deepcopy(specification),
                      "material_ready":record["review_material_ready"]}
                task["task_id"]=digest(task)
                tasks.append(task)
        cursor=page["next_offset"]
        if cursor is None:
            break
        if type(cursor) is not int or cursor<=page["offset"]:
            raise EvidenceError("canonical review cursor did not progress")
    audit=audit_lens_campaign(pages,source_report=source)
    if len(tasks)!=lens_count*len(LANES) or len(tasks)!=len({t["task_id"] for t in tasks}):
        raise EvidenceError("canonical lane coverage mismatch")
    ident=digest({"source":expected_source_digest,"catalog":audit["catalog_digest"],
                  "audit":audit["audit_digest"],"tasks":[t["task_id"] for t in tasks]})
    return WorkIndex(expected_source_digest,audit["catalog_digest"],audit["audit_digest"],ident,tuple(tasks))
