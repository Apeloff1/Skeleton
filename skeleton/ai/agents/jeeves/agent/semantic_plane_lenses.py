"""Deep cross-plane semantic lenses for Jeeves.

This catalog fills reasoning families that were previously represented only by
other Jeeves subsystems (probability, causal inference, information, predictive
control, computation, and metacognition) but not by the unified semantic lens
registry.

Every lens here is an interpretive/query operator. It can organize observations,
generate hypotheses, propose discriminating tests, and emit forecasts. It cannot
create evidence, increase source trust, or establish causation on its own.
"""

from __future__ import annotations

from typing import Iterable, Sequence

from .semantic_extreme_lenses import LensMaturity, RareLensDefinition
from .semantic_lenses import LensFamily, SemanticLensRegistry, SemanticLensSpec, SemanticRole
