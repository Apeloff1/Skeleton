PLANE_CATALOG_VERSION = "plane-v1"


def _p(
    key: str,
    family: LensFamily,
    role: SemanticRole,
    year: int,
    description: str,
    cues: Sequence[str],
    asks: Sequence[str],
    predicts: str,
    failure: str,
    lineage: Sequence[str],
    maturity: LensMaturity,
    warning: str,
    *,
    minimum: int = 1,
    pairwise: bool = False,
    sequential: bool = False,
) -> RareLensDefinition:
    return RareLensDefinition(
        SemanticLensSpec(
            key=key,
            family=family,
            role=role,
            lineage_year=year,
            description=description,
            activation_cues=tuple(cues),
            asks=tuple(asks),
            predicts=predicts,
            failure_mode=failure,
            minimum_observations=minimum,
            pairwise=pairwise,
            sequential=sequential,
            rare=True,
        ),
        tuple(lineage),
        maturity,
        warning,
    )


