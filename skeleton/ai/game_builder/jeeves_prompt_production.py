"""Bridge the canonical original game prompt router into real Jeeves system authoring.

Prompts are intent evidence, not trusted code or autonomous model authority.
The existing offline routing axes select installed engine editors; their
canonical typed schema generates genuine source proposals. Unsupported story,
voice, legal, dialog and art requests remain human/model authoring targets,
never silently converted into false working systems.
"""
from __future__ import annotations

from hashlib import sha256
from typing import Any

from .game_project_workspace import GameWorkspace
from .game_prompt_router import route_game_prompt
from .jeeves_appwide_fabric import (
    AppwideInventory, JeevesAppwideError, digest,
)
from .jeeves_production_wave import JeevesProductionWave

SCHEMA = "skeleton.ai.jeeves_prompt_production.v1"
MAX_PROMPT = 6000
MAX_EDITORS = 16
MAX_OVERRIDES_BYTES = 40_000


class JeevesPromptProduction:
    """Prompt-driven authoring through existing route and editor contracts."""

    def __init__(self, inventory: AppwideInventory, workspace: GameWorkspace):
        if not isinstance(inventory, AppwideInventory):
            raise JeevesAppwideError("source inventory required for Jeeves")
        inventory._require_scanned()
        if not isinstance(workspace, GameWorkspace):
            raise JeevesAppwideError("active original workspace required")
        self.inventory = inventory
        self.workspace = workspace

    def _prepare(self, *, project: Any, prompt: Any,
                 editor_overrides=None, expected_snapshot=None,
                 operator_authorized=False):
        if operator_authorized is not True:
            raise PermissionError("designer must authorize prompt-to-source production")
        if expected_snapshot is not None and expected_snapshot != self.inventory._digest:
            raise JeevesAppwideError("stale Jeeves source inventory")
        if type(prompt) is not str or not 12 <= len(prompt) <= MAX_PROMPT:
            raise JeevesAppwideError("concrete bounded game design prompt required")
        if self.workspace.active() != project:
            raise JeevesAppwideError("selected active project required")
        if editor_overrides is None:
            editor_overrides = {}
        if (type(editor_overrides) is not dict or
                any(type(k) is not str or type(v) is not dict
                    for k, v in editor_overrides.items())):
            raise JeevesAppwideError("typed editor settings overrides required")
        from .jeeves_appwide_fabric import canonical
        if len(canonical(editor_overrides).encode()) > MAX_OVERRIDES_BYTES:
            raise JeevesAppwideError("oversized game design settings")
        routed = route_game_prompt(
            self.workspace, prompt, project=project,
            max_targets=32, authorized=True)
        selected = []
        others = []
        used = set()
        for axis in routed.axes:
            if axis.key.startswith("system_") and axis.engine == "system":
                editor = axis.key[len("system_"):]
                if editor not in used and len(selected) < MAX_EDITORS:
                    selected.append({
                        "editor": editor,
                        "settings": editor_overrides.get(editor, {}),
                    })
                    used.add(editor)
            else:
                others.append({
                    "axis": axis.key,
                    "candidate_paths": list(axis.targets),
                    "model_authored_source_not_claimed": True,
                })
        if not selected:
            raise JeevesAppwideError(
                "prompt needs a concrete installed game engine/genre for source generation")
        if set(editor_overrides) - used:
            raise JeevesAppwideError(
                "editor override references an engine not selected by prompt")
        plan = JeevesProductionWave(
            self.inventory, self.workspace
        ).plan(
            project=project, phase="systems", items=selected,
            expected_snapshot=expected_snapshot)
        body = {
            "schema": SCHEMA + ".plan",
            "project": project,
            "inventory_snapshot": self.inventory._digest,
            "prompt_sha256": sha256(prompt.encode("utf-8")).hexdigest(),
            "canonical_prompt_router_digest": routed.digest,
            "canonical_prompt_target_count": len(routed.files),
            "installed_editor_source_items": selected,
            "editor_count": len(selected),
            "non_editor_axes_not_autogenerated": others,
            "real_original_source_plan": plan,
            "real_source_plan_digest": plan["digest"],
            "language_model_called": False,
            "generic_original_story_dialogue_or_art_not_auto_generated": True,
            "source_edits_not_committed": True,
        }
        return {**body, "digest": digest(body)}, selected

    def plan(self, *, project, prompt, editor_overrides=None,
             expected_snapshot=None, operator_authorized=False):
        receipt, _ = self._prepare(
            project=project, prompt=prompt,
            editor_overrides=editor_overrides,
            expected_snapshot=expected_snapshot,
            operator_authorized=operator_authorized)
        return receipt

    def stage(self, *, project, prompt, editor_overrides=None,
              expected_prompt_plan_digest, reason,
              expected_snapshot=None, operator_authorized=False):
        if operator_authorized is not True:
            raise PermissionError("operator must explicitly approve game source staging")
        if (type(expected_prompt_plan_digest) is not str or
                len(expected_prompt_plan_digest) != 64):
            raise JeevesAppwideError("exact prompt-to-editor plan digest required")
        receipt, selected = self._prepare(
            project=project, prompt=prompt,
            editor_overrides=editor_overrides,
            expected_snapshot=expected_snapshot,
            operator_authorized=True)
        if receipt["digest"] != expected_prompt_plan_digest:
            raise JeevesAppwideError("prompt intent or original source plan changed")
        staged = JeevesProductionWave(
            self.inventory, self.workspace
        ).stage(
            project=project, phase="systems", items=selected,
            expected_plan_digest=receipt["real_source_plan_digest"],
            reason=reason, expected_snapshot=expected_snapshot,
            operator_authorized=True)
        body = {
            "schema": SCHEMA + ".stage",
            "project": project,
            "source_prompt_plan_digest": receipt["digest"],
            "source_plan_digest": receipt["real_source_plan_digest"],
            "proposal_count": staged["proposal_count"],
            "proposals": staged["proposals"],
            "unmatched_non_system_axes": receipt["non_editor_axes_not_autogenerated"],
            "human_commit_required": True,
            "source_files_committed": 0,
            "model_output_misrepresented": False,
        }
        return {**body, "digest": digest(body)}
