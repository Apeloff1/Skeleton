"""Full original NPC roster authoring: cast, traits, motives, home/work and lore.

Strict human-reviewed JSON editing without executable plugins, foreign
characters or invented runtime observations. Provenance separates designer
backstory from witnessed memory generated by the actual game simulator.
"""
from __future__ import annotations

from dataclasses import dataclass
from hashlib import sha256
from pathlib import Path
import json

from .contracts import canonical_json
from .quest_scene_engine import DirectorWorld
from .npc_society_runtime import (
    Citizen, Memory, Mind, Society, SocietyError, ROLES,
    make_society,
)
from .authored_tiles import _no_duplicate_keys, _json_number_reject


class CitizenAuthoringError(ValueError):
    """Authored NPC roster is ambiguous or inconsistent with the game."""


NPC_SCHEMA = "skeleton.game_builder.original_citizen_roster.v1"
MAX_BYTES = 850000


@dataclass(frozen=True,slots=True)
class ApprovedRoster:
    society: Society
    source_sha256: str
    authored_biography_count: int

    def evidence(self):
        return dict(schema="skeleton.game_builder.citizen_roster_handoff.v1",
                    world_digest=self.society.world_digest,
                    roster_digest=self.society.digest,
                    source_sha256=self.source_sha256,
                    population=len(self.society.profiles),
                    authored_biographies=self.authored_biography_count,
                    custom_schedules_approved=True,
                    script_execution=False,
                    external_model_generation=False,
                    copyright_review_automated=False,
                    publication_approved=False)


def npc_template(world: DirectorWorld,population: int,*,authorized: bool) -> dict:
    if not authorized:
        raise PermissionError("citizen template authoring requires operator authority")
    society=make_society(world,population,authorized=True)
    return dict(schema=NPC_SCHEMA,world_digest=world.digest,
                profiles=[p.payload() for p in society.profiles],
                minds=[m.payload() for m in society.minds])


def _dictionary(data,keys):
    if type(data) is not dict or set(data)!=set(keys):
        raise CitizenAuthoringError("unknown or missing authored citizen fields")
    return data


def compile_npc_roster(world: DirectorWorld,document: dict,*,
                       human_reviewed: bool,authorized: bool) -> ApprovedRoster:
    if not authorized:
        raise PermissionError("custom original actors require operator authority")
    if human_reviewed is not True:
        raise CitizenAuthoringError("independent human review required for original actors")
    if not isinstance(world,DirectorWorld):
        raise CitizenAuthoringError("typed original world is required")
    _dictionary(document,("schema","world_digest","profiles","minds"))
    if document["schema"]!=NPC_SCHEMA or document["world_digest"]!=world.digest:
        raise CitizenAuthoringError("original NPC roster changed game identity")
    rows=document["profiles"]; states=document["minds"]
    if (type(rows) is not list or type(states) is not list
            or not 3<=len(rows)<=512 or len(rows)!=len(states)):
        raise CitizenAuthoringError("NPC population requires 3..512 unique actors")
    scenes={s.key for s in world.scenes}
    profiles=[]
    for row in rows:
        d=_dictionary(row,(
            "key","name","profession","faction","home","workplace",
            "meeting_place","motive","bravery","empathy","curiosity","diligence",
        ))
        try:
            profile=Citizen(**d)
        except (SocietyError,TypeError,ValueError) as exc:
            raise CitizenAuthoringError("invalid original NPC personality") from exc
        if any(x not in scenes for x in (
            profile.home,profile.workplace,profile.meeting_place,
        )):
            raise CitizenAuthoringError("NPC schedules reference imaginary scenes")
        if profile.profession not in ROLES:
            raise CitizenAuthoringError("profession has no real supported simulation")
        profiles.append(profile)
    keys={p.key for p in profiles}
    if len(keys)!=len(profiles):
        raise CitizenAuthoringError("duplicate original character key")
    minds=[]
    biographies=0
    for row in states:
        d=_dictionary(row,(
            "key","scene","energy","hunger","stress","belonging",
            "skill","supplies","intent","memories","bonds","belief_flags","lod",
        ))
        if d["key"] not in keys or d["scene"] not in scenes:
            raise CitizenAuthoringError("NPC runtime belongs to another world")
        if type(d["memories"]) is not list or len(d["memories"])>24:
            raise CitizenAuthoringError("authored biographies exceed memory budget")
        memories=[]
        for memory in d["memories"]:
            m=_dictionary(memory,(
                "event","subject","scene","turn","valence","certainty","origin",
            ))
            try:
                entry=Memory(**m)
            except (SocietyError,ValueError,TypeError) as exc:
                raise CitizenAuthoringError("invalid actor memory fact") from exc
            if (entry.origin!="authored_canon" or entry.turn!=0
                    or entry.scene not in scenes or entry.certainty>75):
                raise CitizenAuthoringError(
                    "authored backstory cannot pretend to be a witnessed event"
                )
            memories.append(entry)
            biographies+=1
        if type(d["bonds"]) is not list or any(
            type(b) is not list or len(b)!=2 or b[0] not in keys|{"hero"}
            for b in d["bonds"]
        ):
            raise CitizenAuthoringError("relationship target missing from original cast")
        try:
            minds.append(Mind(
                key=d["key"],scene=d["scene"],energy=d["energy"],
                hunger=d["hunger"],stress=d["stress"],
                belonging=d["belonging"],skill=d["skill"],
                supplies=d["supplies"],intent=d["intent"],
                memories=tuple(memories),
                bonds=tuple((key,score) for key,score in d["bonds"]),
                belief_flags=tuple(d["belief_flags"]),lod=d["lod"],
            ))
        except (SocietyError,TypeError,ValueError) as exc:
            raise CitizenAuthoringError("invalid original NPC psychological state") from exc
    try:
        society=Society(world.digest,world.digest,
                        tuple(profiles),tuple(minds))
    except (SocietyError,TypeError) as exc:
        raise CitizenAuthoringError("NPC identity or psychological roster incompatible") from exc
    payload=(canonical_json(document)+"\n").encode()
    if len(payload)>MAX_BYTES:
        raise CitizenAuthoringError("custom NPC library exceeds input budget")
    return ApprovedRoster(society,sha256(payload).hexdigest(),biographies)


def read_npc_roster(world: DirectorWorld,source: str|Path,*,
                    human_reviewed: bool,authorized: bool) -> ApprovedRoster:
    if not authorized:
        raise PermissionError("reviewed NPC roster handoff requires authority")
    file=Path(source)
    if file.is_symlink() or not file.is_file() or file.stat().st_size>MAX_BYTES:
        raise CitizenAuthoringError("local regular original NPC JSON under 850KB required")
    data=file.read_bytes()
    if len(data)>MAX_BYTES:
        raise CitizenAuthoringError("input document exceeds bounded NPC authoring budget")
    try:
        content=json.loads(data.decode("utf-8","strict"),
                           object_pairs_hook=_no_duplicate_keys,
                           parse_constant=_json_number_reject)
    except (ValueError,UnicodeError,TypeError) as exc:
        raise CitizenAuthoringError("duplicate, ambiguous or invalid NPC JSON rejected") from exc
    return compile_npc_roster(world,content,human_reviewed=human_reviewed,
                              authorized=True)


