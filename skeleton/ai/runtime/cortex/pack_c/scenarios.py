def scenario_by_id(sid: str) -> Optional[Mapping[str, Any]]:
    for row in SCENARIO_CATALOG:
        if row["id"] == sid:
            return row
    return None

def scenarios_for_family(family: str) -> Tuple[Mapping[str, Any], ...]:
    return tuple(r for r in SCENARIO_CATALOG if r["family"] == family)

def assert_catalog_locks() -> None:
    for row in SCENARIO_CATALOG:
        assert row["pfc_attn"] is False
        assert row["expect_unfitted_kind"] == "own"
