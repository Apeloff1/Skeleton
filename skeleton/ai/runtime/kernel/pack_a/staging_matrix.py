def validate_matrix_sample(limit: int = 50) -> int:
    """Return count of rows whose class mapping is consistent."""
    ok = 0
    for i, (rc, sz) in enumerate(STAGING_MATRIX):
        if i >= limit:
            break
        cls = expected_class(sz)
        ms = expected_min_size(rc, sz)
        assert ms >= sz
        assert cls in {c.name for c in Class}
        ok += 1
    return ok


