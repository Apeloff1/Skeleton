def _load() -> Mapping[str, OriginalWorld]:
    worlds: dict[str, OriginalWorld] = {}
    signatures: set[str] = set()
    for domain, rows in sorted(_WORLD_ROWS.items()):
        for index, row in enumerate(rows, start=1):
            title, invariant, lever, ending = row.split("|")
            if ending not in ENDING_POLICIES:
                raise ValueError(f"unknown ending policy for {title}")
            signature = invariant.casefold().strip()
            if signature in signatures:
                raise ValueError(f"reused world invariant: {title}")
            signatures.add(signature)
            identifier = f"{domain}-{index:02d}"
            worlds[identifier] = OriginalWorld(identifier, title, domain, invariant, lever, ending)
    return MappingProxyType(worlds)


WORLDS = _load()


def get_world(world_id: str) -> OriginalWorld:
    try:
        return WORLDS[world_id]
    except (KeyError, TypeError) as exc:
        raise ValueError("unknown original world") from exc
