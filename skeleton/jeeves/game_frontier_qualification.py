"""Governed P1/P3 data contracts for *real* game world-model inference evidence.

This does not load model weights or bypass skeleton.provider_runtime. Inference
and simulation remain with existing canonical owners. These data-only checks
must not be mistaken for external attestation or model-success certification.
"""
from __future__ import annotations

from dataclasses import dataclass
from hashlib import sha256
import json
import math
from typing import Iterable, Mapping

from .game_frontier_dynamics import FPS_MODES


class FrontierQualificationError(ValueError):
    pass


def _digest(value: str, label: str) -> str:
    if not isinstance(value, str) or len(value) != 64 or any(c not in "0123456789abcdef" for c in value):
        raise FrontierQualificationError(f"{label} requires lowercase SHA-256")
    return value


def _token(value: str, label: str) -> str:
    if not isinstance(value, str) or not value or len(value) > 160 or value != value.strip():
        raise FrontierQualificationError(f"{label} requires canonical token")
    return value


def _integer(value: int, label: str, low: int, high: int) -> int:
    if type(value) is not int or not low <= value <= high:
        raise FrontierQualificationError(f"{label} outside [{low},{high}]")
    return value


@dataclass(frozen=True)
class WorldModelCheckpoint:
    model_id: str
    checkpoint_digest: str
    license_id: str
    authorized_scope: str
    model_family: str
    inference_capabilities: tuple[str, ...]
    weights_present: bool
    provider_route_acknowledged: bool

    def __post_init__(self) -> None:
        for key in ("model_id", "license_id", "authorized_scope", "model_family"):
            _token(getattr(self, key), key)
        _digest(self.checkpoint_digest, "checkpoint_digest")
        if not self.inference_capabilities or len(self.inference_capabilities) > 16:
            raise FrontierQualificationError("capability list required")
        if len(set(self.inference_capabilities)) != len(self.inference_capabilities):
            raise FrontierQualificationError("duplicate capabilities")
        for capability in self.inference_capabilities:
            _token(capability, "capability")
        if type(self.weights_present) is not bool or type(self.provider_route_acknowledged) is not bool:
            raise FrontierQualificationError("checkpoint flags must be booleans")

    def require_ready(self, *, capability: str, allowed_licenses: Iterable[str]) -> None:
        if (not self.weights_present or not self.provider_route_acknowledged
                or capability not in self.inference_capabilities
                or self.license_id not in frozenset(allowed_licenses)):
            raise FrontierQualificationError(
                "real checkpoint weights, approved license, declared capability "
                "and canonical provider route acknowledgement required"
            )


@dataclass(frozen=True)
class WorldFrameRequest:
    scene_digest: str
    checkpoint: WorldModelCheckpoint
    input_observation_digest: str
    input_action_digest: str
    frame_index: int
    presentation_fps: int
    deadline_ns: int

    def __post_init__(self) -> None:
        for key in ("scene_digest", "input_observation_digest", "input_action_digest"):
            _digest(getattr(self, key), key)
        _integer(self.frame_index, "frame_index", 0, 2**63 - 1)
        _integer(self.deadline_ns, "deadline_ns", 0, 2**63 - 1)
        if type(self.presentation_fps) is not int or self.presentation_fps not in FPS_MODES:
            raise FrontierQualificationError("unsupported requested fps")


@dataclass(frozen=True)
class FrameInferenceEvidence:
    """One identity-bound frame generated by an externally authoritative runner."""

    frame_index: int
    source_scene_digest: str
    source_observation_digest: str
    source_action_digest: str
    checkpoint_digest: str
    output_frame_digest: str
    inference_started_ns: int
    inference_finished_ns: int
    presentation_ns: int | None
    executor_receipt_digest: str
    origin: str = "candidate_external_attestation"

    def __post_init__(self) -> None:
        _integer(self.frame_index, "frame_index", 0, 2**63 - 1)
        for key in ("source_scene_digest", "source_observation_digest",
                    "source_action_digest", "checkpoint_digest",
                    "output_frame_digest", "executor_receipt_digest"):
            _digest(getattr(self, key), key)
        for key in ("inference_started_ns", "inference_finished_ns"):
            _integer(getattr(self, key), key, 0, 2**63 - 1)
        if self.inference_finished_ns < self.inference_started_ns:
            raise FrontierQualificationError("negative measured inference time")
        if self.presentation_ns is not None:
            _integer(self.presentation_ns, "presentation_ns", 0, 2**63 - 1)
            if self.presentation_ns < self.inference_finished_ns:
                raise FrontierQualificationError("presented before inference finished")
        if self.origin != "candidate_external_attestation":
            raise FrontierQualificationError("external evidence is not host-verified")


@dataclass(frozen=True)
class FramePerformance:
    requested_fps: int
    measured_generation_fps: float
    measured_presentation_fps: float
    p95_inference_latency_ms: float
    generated_frames: int
    presented_frames: int
    dropped_frames: int
    meets_requested_presentation_fps: bool
    authority: str = "reported_external_receipts_not_host_verified"


def qualify_frame_performance(
    requests: Iterable[WorldFrameRequest],
    responses: Iterable[FrameInferenceEvidence],
    *,
    observation_start_ns: int,
    observation_end_ns: int,
    tolerance: float = 0.05,
) -> FramePerformance:
    """Reject mismatched/replayed receipts and measure, but do not certify them.

    Evidence must separately be attested by a trusted host to claim actual
    neural frame generation. These metrics are evidence *candidates* only.
    """
    reqs = tuple(requests)
    replies = tuple(responses)
    if not reqs or len(reqs) != len(replies) or len(reqs) > 1_000_000:
        raise FrontierQualificationError("bounded one-to-one frame evidence required")
    _integer(observation_start_ns, "start", 0, 2**63 - 1)
    _integer(observation_end_ns, "end", 0, 2**63 - 1)
    if observation_end_ns <= observation_start_ns:
        raise FrontierQualificationError("observation interval must be positive")
    if type(tolerance) not in (int, float) or not math.isfinite(tolerance) or not 0 <= tolerance <= .5:
        raise FrontierQualificationError("invalid FPS tolerance")
    fps = reqs[0].presentation_fps
    if any(r.presentation_fps != fps for r in reqs):
        raise FrontierQualificationError("mixed modes must be measured separately")
    frame_ids = set()
    latencies = []
    presented = 0
    for request, answer in zip(reqs, replies):
        request.checkpoint.require_ready(
            capability="action_conditioned_frame",
            allowed_licenses=(request.checkpoint.license_id,),
        )
        if request.frame_index in frame_ids:
            raise FrontierQualificationError("duplicate/replayed frame index")
        frame_ids.add(request.frame_index)
        if (request.frame_index != answer.frame_index
                or request.scene_digest != answer.source_scene_digest
                or request.input_observation_digest != answer.source_observation_digest
                or request.input_action_digest != answer.source_action_digest
                or request.checkpoint.checkpoint_digest != answer.checkpoint_digest):
            raise FrontierQualificationError("input/checkpoint frame evidence mismatch")
        if not observation_start_ns <= answer.inference_started_ns < observation_end_ns:
            raise FrontierQualificationError("inference started outside measurement interval")
        if answer.inference_finished_ns > observation_end_ns:
            raise FrontierQualificationError("inference finished outside measurement interval")
        if answer.presentation_ns is not None:
            if answer.presentation_ns > observation_end_ns:
                raise FrontierQualificationError("presentation outside measurement interval")
            presented += 1
        latencies.append((answer.inference_finished_ns - answer.inference_started_ns) / 1e6)
    latencies.sort()
    p95 = latencies[math.ceil(len(latencies) * .95) - 1]
    elapsed_s = (observation_end_ns - observation_start_ns) / 1e9
    generated_fps = len(replies) / elapsed_s
    presented_fps = presented / elapsed_s
    return FramePerformance(
        fps, generated_fps, presented_fps, p95, len(replies), presented,
        len(replies) - presented,
        presented_fps >= fps * (1 - tolerance),
    )


@dataclass(frozen=True)
class SimReady3DArtifact:
    mesh_digest: str
    skeleton_digest: str
    animation_digest: str
    collision_digest: str
    material_digests: tuple[str, ...]
    lod_triangle_counts: tuple[int, ...]
    bone_count: int
    animation_frames: int
    sample_simulation_digest: str
    source_rights_digest: str

    def __post_init__(self) -> None:
        for name in ("mesh_digest", "skeleton_digest", "animation_digest",
                     "collision_digest", "sample_simulation_digest", "source_rights_digest"):
            _digest(getattr(self, name), name)
        if not self.material_digests or len(self.material_digests) > 64:
            raise FrontierQualificationError("at least one material evidence digest required")
        for item in self.material_digests:
            _digest(item, "material")
        _integer(self.bone_count, "bone_count", 1, 1024)
        _integer(self.animation_frames, "animation_frames", 2, 1_000_000)
        if not self.lod_triangle_counts or len(self.lod_triangle_counts) > 32:
            raise FrontierQualificationError("LOD chain required")
        for triangles in self.lod_triangle_counts:
            _integer(triangles, "triangles", 1, 100_000_000)
        if any(a < b for a, b in zip(self.lod_triangle_counts,
                                     self.lod_triangle_counts[1:])):
            raise FrontierQualificationError("LOD counts must decrease with distance")

    @property
    def candidate_digest(self) -> str:
        record = {
            "schema": "skeleton.game.sim_ready_3d_candidate.v1",
            "mesh": self.mesh_digest, "skeleton": self.skeleton_digest,
            "animation": self.animation_digest, "collision": self.collision_digest,
            "materials": self.material_digests, "lods": self.lod_triangle_counts,
            "bones": self.bone_count, "frames": self.animation_frames,
            "simulation": self.sample_simulation_digest,
            "rights": self.source_rights_digest,
        }
        return sha256(json.dumps(record, sort_keys=True,
                                 separators=(",", ":")).encode()).hexdigest()


@dataclass(frozen=True)
class RuntimeAdmittance:
    candidate_digest: str
    passed_validation_ids: tuple[str, ...]
    host_test_attestation_digest: str
    operator_approved: bool

    def __post_init__(self) -> None:
        _digest(self.candidate_digest, "candidate_digest")
        _digest(self.host_test_attestation_digest, "host_test_attestation_digest")
        if type(self.operator_approved) is not bool:
            raise FrontierQualificationError("operator_approved must be boolean")
        if len(self.passed_validation_ids) != len(set(self.passed_validation_ids)):
            raise FrontierQualificationError("duplicate validation IDs")

    def qualified_by_contract(self, *, required_ids: Iterable[str]) -> bool:
        """Contract completeness, *not* independent host trust verification."""
        return self.operator_approved and set(required_ids).issubset(set(self.passed_validation_ids))
