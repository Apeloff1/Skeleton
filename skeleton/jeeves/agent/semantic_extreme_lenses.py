def rare_semantic_specs() -> tuple[SemanticLensSpec, ...]:
    return tuple(item.spec for item in rare_semantic_definitions())


def register_rare_lenses(registry: SemanticLensRegistry, *, ignore_existing: bool = True) -> SemanticLensRegistry:
    if not isinstance(registry, SemanticLensRegistry):
        raise TypeError("registry must be SemanticLensRegistry")
    existing = {item.key for item in registry.all()}
    for definition in rare_semantic_definitions():
        if definition.spec.key in existing:
            if ignore_existing:
                continue
            raise AgentContractError(f"duplicate rare semantic lens: {definition.spec.key}")
        registry.register(definition.spec)
        existing.add(definition.spec.key)
    return registry


def definitions_by_family(definitions: Iterable[RareLensDefinition] | None = None) -> dict[LensFamily, tuple[RareLensDefinition, ...]]:
    items = tuple(definitions or rare_semantic_definitions())
    grouped: dict[LensFamily, list[RareLensDefinition]] = {}
    for item in items:
        grouped.setdefault(item.spec.family, []).append(item)
    return {family: tuple(sorted(values, key=lambda x: (x.spec.lineage_year, x.spec.key))) for family, values in grouped.items()}