class LensMaturity(str, Enum):
    FORMAL = "formal"
    EMPIRICAL = "empirical"
    MIXED = "mixed"
    CONCEPTUAL = "conceptual"
    HEURISTIC = "heuristic"


@dataclass(frozen=True, slots=True)
class RareLensDefinition:
    spec: SemanticLensSpec
    lineage: tuple[str, ...]
    maturity: LensMaturity
    transfer_warning: str

    def __post_init__(self) -> None:
        if not isinstance(self.spec, SemanticLensSpec):
            raise AgentContractError("spec must be SemanticLensSpec")
        lineage = tuple(str(item).strip() for item in self.lineage if str(item).strip())
        if not lineage:
            raise AgentContractError("rare lens requires lineage")
        object.__setattr__(self, "lineage", lineage)
        if not isinstance(self.maturity, LensMaturity):
            object.__setattr__(self, "maturity", LensMaturity(str(self.maturity)))
        object.__setattr__(self, "transfer_warning", bounded_text("transfer_warning", self.transfer_warning, maximum=4096))


def _d(
    key: str, family: LensFamily, role: SemanticRole, year: int, description: str,
    cues: Sequence[str], asks: Sequence[str], predicts: str, failure: str,
    lineage: Sequence[str], maturity: LensMaturity, warning: str, *,
    minimum: int = 1, pairwise: bool = False, sequential: bool = False,
) -> RareLensDefinition:
    spec = SemanticLensSpec(
        key=key, family=family, role=role, lineage_year=year, description=description,
        activation_cues=tuple(cues), asks=tuple(asks), predicts=predicts, failure_mode=failure,
        minimum_observations=minimum, pairwise=pairwise, sequential=sequential, rare=True,
    )
    return RareLensDefinition(spec, tuple(lineage), maturity, warning)


