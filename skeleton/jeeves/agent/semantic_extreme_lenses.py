"""Extreme semantic lenses for perpendicular Jeeves reasoning.

This module expands the semantic catalog with rare operators drawn from film
editing/cognition, narratology/pragmatics, game studies/game theory, and memory
science. Lenses are hypothesis generators, never evidence generators.

Every definition carries intellectual lineage, epistemic maturity, a transfer
warning, a falsifiable prediction, and a named failure mode. This deliberately
does not pretend that film/literary/game studies form one canonical taxonomy.
"""

