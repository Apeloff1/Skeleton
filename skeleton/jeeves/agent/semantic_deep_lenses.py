"""Deep rare semantic lenses for Jeeves.

These lenses extend the ordinary and frontier semantic catalogs with deliberately
uncommon operators from film editing, narratology, literary theory, pragmatics,
game studies, and cross-domain systems reasoning.

A lens is a hypothesis generator, not evidence. Each lens therefore carries an
operational question, a forward prediction, and a named failure mode. The
lineage metadata records intellectual ancestry without claiming that an exact
modern formulation was invented in the orientation year.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Mapping, Sequence

from .semantic_lenses import LensFamily, SemanticLensSpec, SemanticRole


@dataclass(frozen=True, slots=True)
class DeepLensLineage:
    key: str
    lineage: tuple[str, ...]
    source_hint: str
    boundary: str


def _lens(
    key: str,
    family: LensFamily,
    role: SemanticRole,
    year: int,
    description: str,
    cues: Sequence[str],
    asks: Sequence[str],
    predicts: str,
    failure: str,
    *,
    minimum: int = 1,
    pairwise: bool = False,
    sequential: bool = False,
) -> SemanticLensSpec:
    return SemanticLensSpec(
        key=key,
        family=family,
        role=role,
        lineage_year=year,
        description=description,
        activation_cues=tuple(cues),
        asks=tuple(asks),
        predicts=predicts,
        failure_mode=failure,
        minimum_observations=minimum,
        pairwise=pairwise,
        sequential=sequential,
        rare=True,
    )


