def _load_known_seam(name: str):
    loader = _REGISTERED_SEAM_LOADERS.get(name)
    if loader is None:
        raise ImportError("unregistered local-AI seam")
    return loader()

class GapFiller:
    def __init__(self):
        self.seams: Dict[str, Callable] = {}
        self._load_core()
        self._load_numbered()

    def _load_core(self):
        for name in SEAMS:
            try:
                mod = _load_known_seam(name)
                if hasattr(mod, "process"):
                    self.seams[name] = mod.process
            except Exception:
                pass

    def _load_numbered(self):
        for i in range(200):
            name = f"seam_{i:03d}"
            try:
                mod = _load_known_seam(name)
                func = getattr(mod, f"process_{i}", None)
                if func:
                    self.seams[name] = func
            except Exception:
                continue

    def call(self, name: str, data: dict) -> dict:
        if name in self.seams:
            return self.seams[name](data)
        return {"error": "seam not found", "name": name}

    def list(self) -> list:
        return list(self.seams.keys())
