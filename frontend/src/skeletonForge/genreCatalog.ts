/** Search all genres regardless of selected category; category only limits browsing. */
export function filterGenreChoices(query: string, family = 'popular'): string[] {
  const term = String(query || '').toLowerCase().trim().replace(/[_\s]+/g, '-');
  const source = term || family === 'all'
    ? GENRE_CHOICES
    : family === 'popular'
      ? POPULAR_GENRES
      : [...(GENRE_GROUPS.find((group) => group.id === family)?.genres || [])];
  return term ? source.filter((token) => token.includes(term)) : [...source];
}
