"""Explicit fail-closed Dragon Mongo cutover, isolated from account authority."""
from __future__ import annotations

import hashlib
import os
from pathlib import Path
from core.dragon_graph_deployment import _read_json,_json
from core.dragon_mongo_relocation import COLLECTIONS,JOURNAL,MARKER,HEX,_name,RelocationHeld


def requested():
    return os.getenv("SKL_DRAGON_MONGO_CUTOVER","").strip() not in ("","0") or bool(os.getenv("SKL_DRAGON_MONGO_CUTOVER_RECEIPT","").strip())


def load_receipt(source_db):
    if os.getenv("SKL_DRAGON_MONGO_CUTOVER","").strip()!="1":
        raise RelocationHeld("explicit cutover switch required")
    raw=os.getenv("SKL_DRAGON_MONGO_CUTOVER_RECEIPT","").strip()
    name=_name(os.getenv("SKL_DRAGON_TARGET_MONGO_DB","").strip())
    if not raw or name==source_db or not os.getenv("SKL_DRAGON_TARGET_MONGO_URL","").strip():
        raise RelocationHeld("complete cutover configuration required")
    receipt=_read_json(Path(raw))
    keys={"version","source_db","target_db","source","target","verified","receipt_sha","source_retained","live_cutover_executed"}
    if (not isinstance(receipt,dict) or set(receipt)!=keys or receipt["version"]!=1 or receipt["verified"] is not True
            or receipt["source_retained"] is not True or receipt["live_cutover_executed"] is not False
            or receipt["source_db"]!=source_db or receipt["target_db"]!=name
            or not isinstance(receipt["source"],dict) or set(receipt["source"])!=set(COLLECTIONS)
            or not isinstance(receipt["target"],dict) or set(receipt["target"])!=set(COLLECTIONS)):
        raise RelocationHeld("cutover receipt binding differs")
    subset={k:receipt[k] for k in ("version","source_db","target_db","source","target","verified")}
    if receipt["receipt_sha"]!=hashlib.sha256(_json(subset)).hexdigest():
        raise RelocationHeld("cutover receipt hash differs")
    for coll in COLLECTIONS:
        source=receipt["source"][coll];target=receipt["target"][coll]
        if not isinstance(source,dict) or set(source)!={"uuid","index_sha","data"}:
            raise RelocationHeld("cutover source shape differs")
        if not isinstance(target,str) or len(target)!=32 or any(c not in "0123456789abcdef" for c in target):
            raise RelocationHeld("cutover target UUID differs")
        if not isinstance(source["uuid"],str) or len(source["uuid"])!=32 or source["uuid"]==target:
            raise RelocationHeld("cutover UUID alias")
        if not isinstance(source["index_sha"],str) or not HEX.fullmatch(source["index_sha"]):
            raise RelocationHeld("cutover index witness differs")
        data=source["data"]
        if not isinstance(data,dict) or set(data)!={"documents","bytes","sha256"} or any(type(data[k]) is not int or data[k]<0 for k in ("documents","bytes")) or not isinstance(data["sha256"],str) or not HEX.fullmatch(data["sha256"]):
            raise RelocationHeld("cutover content witness differs")
    return receipt


async def verify_remote(target,receipt):
    # Only topology/custody is checked on startup; the full BSON data
    # witness was generated by offline verify. Subsequent legitimate
    # writes must not be compared against the pre-cutover content snapshot.
    if target.name!=receipt["target_db"]:raise RelocationHeld("cutover target namespace differs")
    hello=await target.command("hello",maxTimeMS=3000)
    if hello.get("msg")=="isdbgrid" or not hello.get("isWritablePrimary"):
        raise RelocationHeld("cutover target must be an ordinary writable Mongo primary")
    await target.command("ping",maxTimeMS=3000)
    journal=await target[JOURNAL].find_one({"_id":MARKER},max_time_ms=3000)
    if (not journal or journal.get("phase")!="verified" or journal.get("receipt_sha")!=receipt["receipt_sha"]
            or journal.get("source_db")!=receipt["source_db"] or journal.get("target_db")!=target.name
            or journal.get("source")!=receipt["source"] or journal.get("target")!=receipt["target"]):
        raise RelocationHeld("remote cutover marker differs")
    for coll in COLLECTIONS:
        info=await target.command({"listCollections":1,"filter":{"name":coll},"nameOnly":False,"maxTimeMS":3000})
        rows=info.get("cursor",{}).get("firstBatch",[])
        if len(rows)!=1 or rows[0].get("type")!="collection" or rows[0].get("options"):
            raise RelocationHeld("remote collection topology differs")
        uuid=rows[0].get("info",{}).get("uuid")
        if uuid is None or bytes(uuid).hex()!=receipt["target"][coll]:
            raise RelocationHeld("remote collection replaced")
    return True


async def activate(source,client=None):
    from core.databases import _ActiveLoopMotorClient
    receipt=load_receipt(source.name)
    owned=client is None
    if owned:
        client=_ActiveLoopMotorClient(os.environ["SKL_DRAGON_TARGET_MONGO_URL"],
            connect=False,serverSelectionTimeoutMS=5000,connectTimeoutMS=5000,
            socketTimeoutMS=20000,maxPoolSize=32,retryWrites=True,retryReads=True,
            w="majority",journal=True,appname="dragon-dedicated-authority")
    try:
        target=client[receipt["target_db"]]
        await verify_remote(target,receipt)
        return client,target
    except BaseException:
        if owned and client is not None:client.close()
        raise
