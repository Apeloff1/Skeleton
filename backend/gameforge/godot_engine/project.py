"""
godot_engine.project — scaffold Godot 4 projects from structured specs.

Generates a complete, runnable project directory:

    <project>/
    |-- project.godot          # engine config (renderer, main scene, input)
    |-- icon.svg               # default icon
    |-- scenes/
    |   `-- main.tscn          # main scene with a Camera + root node
    `-- scripts/
        `-- main.gd            # entry script (extends the root node)

The spec format is intentionally small — pipelines (Text-to-NPC,
Text-to-Game-Logic, etc.) emit their own rich JSON, and this module is the
single place that turns a *game* spec into *engine* files.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

GODOT_CONFIG_VERSION = 5  # Godot 4.x

_ICON_SVG = (
    '<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128">'
    '<rect width="128" height="128" rx="24" fill="#478cbf"/>'
    '<text x="64" y="78" font-size="52" text-anchor="middle" '
    'fill="#fff" font-family="sans-serif">T</text></svg>'
)

_MAIN_SCENE = """[gd_scene load_steps=2 format=3 uid="uid://tutolage_main"]

[ext_resource type="Script" path="res://scripts/main.gd" id="1"]

[node name="Main" type="Node2D"]
script = ExtResource("1")

[node name="Camera2D" type="Camera2D" parent="."]
zoom = Vector2(1, 1)
"""

_MAIN_SCRIPT_TEMPLATE = '''"""
{title} — generated by Tutolage Godot Engine.
"""
extends Node2D


func _ready() -> void:
    print("{title}: ready")


func _process(_delta: float) -> void:
    pass
'''


def _slug(name: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9_]+", "_", name.strip().lower()).strip("_")
    return s or "tutolage_game"


@dataclass
class ProjectSpec:
    """Everything needed to scaffold a runnable Godot project."""

    title: str
    description: str = ""
    main_scene: str = "res://scenes/main.tscn"
    renderer: str = "gl_compatibility"        # forward_plus | mobile | gl_compatibility
    window_width: int = 1280
    window_height: int = 720
    features: list[str] = field(default_factory=lambda: ["4.2"])
    autoloads: dict[str, str] = field(default_factory=dict)  # name -> res:// path
    input_actions: dict[str, list[str]] = field(default_factory=dict)  # action -> keys


@dataclass
class ScaffoldResult:
    project_dir: Path
    files_written: list[str]
    slug: str

    def to_dict(self) -> dict:
        return {
            "project_dir": str(self.project_dir),
            "slug": self.slug,
            "files_written": self.files_written,
            "file_count": len(self.files_written),
        }


def _render_project_godot(spec: ProjectSpec) -> str:
    lines: list[str] = [
        "; Engine configuration file.",
        "; Generated by Tutolage godot_engine.project — edit via the API, not by hand.",
        "",
        "config_version=5",
        "",
        "[application]",
        "",
        f'config/name="{spec.title}"',
        f'config/description="{spec.description}"',
        "config/features=PackedStringArray(" + ", ".join(f'"{f}"' for f in spec.features) + ")",
        f'run/main_scene="{spec.main_scene}"',
        'icon="res://icon.svg"',
        "",
        "[display]",
        "",
        f"window/size/viewport_width={spec.window_width}",
        f"window/size/viewport_height={spec.window_height}",
        "",
        "[rendering]",
        "",
        f'renderer/rendering_method="{spec.renderer}"',
    ]
    if spec.autoloads:
        lines += ["", "[autoloads]", ""]
        lines += [f'{name}="*{path}"' for name, path in spec.autoloads.items()]
    if spec.input_actions:
        lines += ["", "[input]", ""]
        for action, keys in spec.input_actions.items():
            events = ", ".join(
                'Object(InputEventKey,"resource_local_to_scene":false,'
                f'"keycode":{key},"script":null)' for key in keys
            )
            lines.append(f"{action}={{\"deadzone\": 0.5, \"events\": [{events}]}}")
    return "\n".join(lines) + "\n"


def scaffold_project(spec: ProjectSpec, root: Path) -> ScaffoldResult:
    """Write a complete Godot project under ``root/<slug>/``."""
    slug = _slug(spec.title)
    project_dir = root / slug
    files: dict[Path, str] = {
        project_dir / "project.godot": _render_project_godot(spec),
        project_dir / "icon.svg": _ICON_SVG,
        project_dir / "scenes" / "main.tscn": _MAIN_SCENE,
        project_dir / "scripts" / "main.gd": _MAIN_SCRIPT_TEMPLATE.format(title=spec.title),
    }
    written: list[str] = []
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(str(path.relative_to(project_dir)))
    return ScaffoldResult(project_dir=project_dir, files_written=written, slug=slug)
