#!/usr/bin/env python3
"""Generate docs/api/API_V1_ROUTES.md from create_app()'s real route table.

Columns: method, path, auth/seal class, router module (endpoint __module__).
Auth classes are derived from the app's own GatePolicy:
  * ``open``          -- matches the gate's open prefixes (no x-gf-seal needed)
  * ``engine-bearer`` -- /api/v1/engine: open to the HMAC gate but guarded by the
                         engine's own service-to-service bearer + principal check
  * ``sealed``        -- everything else: fail-closed x-gf-seal HMAC (install_gate)

Usage: python scripts/gen_api_v1_reference.py [--check]
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "api" / "API_V1_ROUTES.md"
PREFIX = "/api/v1"


def _walk(routes, prefix: str = ""):
    from fastapi.routing import APIRoute, APIWebSocketRoute
    for route in routes:
        original = getattr(route, "original_router", None)
        if original is not None:  # FastAPI lazy _IncludedRouter
            extra = getattr(getattr(route, "include_context", None), "prefix", "") or ""
            yield from _walk(original.routes, prefix + extra)
            continue
        if isinstance(route, (APIRoute, APIWebSocketRoute)):
            endpoint = getattr(route, "endpoint", None)
            module = getattr(endpoint, "__module__", "?")
            methods = sorted(getattr(route, "methods", None) or {"WS"})
            yield prefix + route.path, methods, module


def collect_rows() -> list[tuple[str, str, str, str]]:
    sys.path.insert(0, str(ROOT))
    os.environ.setdefault("SKELETON_OMNIFABRIC_API", "1")
    from skeleton.api.middleware import GatePolicy
    from skeleton.api.server import _gate_open_prefixes, create_app

    app = create_app()
    policy = GatePolicy(open_prefixes=_gate_open_prefixes())
    rows = set()
    for path, methods, module in _walk(app.routes):
        if not (path == PREFIX or path.startswith(PREFIX + "/")):
            continue
        if path == "/api/v1/engine" or path.startswith("/api/v1/engine/"):
            auth = "engine-bearer"
        elif policy.is_open_route(path):
            auth = "open"
        else:
            auth = "sealed"
        for m in methods:
            if m == "HEAD":
                continue
            rows.add((path, m, auth, module))
    return sorted(rows)


def render(rows) -> str:
    lines = [
        "# /api/v1 route reference",
        "",
        "<!-- GENERATED by scripts/gen_api_v1_reference.py from create_app(); do not edit. -->",
        "<!-- Regenerate: python scripts/gen_api_v1_reference.py -->",
        "",
        "Auth classes: `open` = gate open prefix; `sealed` = fail-closed `x-gf-seal` HMAC via",
        "`install_gate`; `engine-bearer` = exempt from the HMAC gate, guarded by the engine",
        "service bearer token and principal validation. Generated with the default",
        "environment (OmniFabric mounted, public dev surfaces off).",
        "",
        f"Total: {len(rows)} method/path pairs.",
        "",
        "| Method | Path | Auth | Router module |",
        "|---|---|---|---|",
    ]
    for path, method, auth, module in rows:
        lines.append(f"| {method} | `{path}` | {auth} | `{module}` |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the doc is stale")
    args = ap.parse_args(argv)
    text = render(collect_rows())
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run scripts/gen_api_v1_reference.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
