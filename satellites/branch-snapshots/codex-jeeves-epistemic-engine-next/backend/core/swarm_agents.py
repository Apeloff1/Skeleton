def find_relevant(keywords: list[str], limit: int = 6) -> list[dict]:
    """Return agents whose expertise best overlaps the provided keywords."""
    kw = {k.lower() for k in keywords if isinstance(k, str)}
    scored: list[tuple[int, dict]] = []
    for d in SWARM_DOMAINS:
        exp_set = {e.lower() for e in d["expertise"]}
        hit = len(kw & exp_set)
        # bonus hits by category name / domain name substrings
        for k in kw:
            if k in d["category"] or k in d["domain"].lower():
                hit += 1
        if hit > 0:
            scored.append((hit, d))
    scored.sort(key=lambda t: -t[0])
    return [d for _, d in scored[:limit]]


def pick_balanced(n: int = 5) -> list[dict]:
    """Round-robin across categories to ensure diverse voice."""
    out: list[dict] = []
    cats = list(BY_CATEGORY.keys())
    i = 0
    while len(out) < n and i < n * len(cats):
        cat = cats[i % len(cats)]
        bucket = BY_CATEGORY[cat]
        if bucket:
            agent = bucket[(i // len(cats)) % len(bucket)]
            if agent not in out:
                out.append(agent)
        i += 1
    return out
