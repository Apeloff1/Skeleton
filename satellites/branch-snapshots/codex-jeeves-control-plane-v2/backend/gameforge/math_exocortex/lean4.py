from __future__ import annotations
"""
Lean 4 formal verification bridge — mathematical certainty via proof obligations.

Uses `lake` / `lean` when available; otherwise records structured obligations and
proof skeletons for offline completion. Full audit log of every interaction.
"""

import hashlib
import os
import shutil
import subprocess
import tempfile
import textwrap
import uuid
from dataclasses import dataclass, field, asdict
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional


@dataclass
class ProofObligation:
    obligation_id: str
    statement: str
    context: str
    lean_source: str
    status: str  # pending | proved | failed | sorry | unavailable
    result_message: str = ""
    created_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())
    finished_at: Optional[str] = None
    backend: str = "lean4"

    def to_dict(self) -> dict:
        return asdict(self)


class Lean4Log:
    def __init__(self):
        self.entries: List[Dict[str, Any]] = []

    def add(self, event: str, **kwargs):
        self.entries.append(
            {"ts": datetime.utcnow().isoformat(), "event": event, **kwargs}
        )
        if len(self.entries) > 5000:
            self.entries = self.entries[-5000:]

    def tail(self, n: int = 30) -> List[Dict[str, Any]]:
        return self.entries[-n:]


class Lean4Verifier:
    """
    Enterprise Lean 4 integration.

    Environment:
      GAMEFORGE_LEAN_BIN   — path to lean executable
      GAMEFORGE_LAKE_BIN   — path to lake
      GAMEFORGE_LEAN_WORK  — workspace dir for generated .lean files
    """

    def __init__(self):
        self.log = Lean4Log()
        self.obligations: Dict[str, ProofObligation] = {}
        self.lean_bin = os.getenv("GAMEFORGE_LEAN_BIN") or shutil.which("lean")
        self.lake_bin = os.getenv("GAMEFORGE_LAKE_BIN") or shutil.which("lake")
        base = Path(os.getenv("GAMEFORGE_LEAN_WORK", os.getenv("GAMEFORGE_DATA_DIR", "/tmp/gameforge_data")))
        self.work = base / "lean4_work"
        self.work.mkdir(parents=True, exist_ok=True)
        self.log.add(
            "init",
            lean_bin=self.lean_bin,
            lake_bin=self.lake_bin,
            work=str(self.work),
            available=bool(self.lean_bin),
        )

    @property
    def available(self) -> bool:
        return bool(self.lean_bin)

    def _skeleton(self, statement: str, context: str = "") -> str:
        """
        Generate a minimal Lean 4 theorem file.
        Statement should be a Lean proposition fragment, e.g.:
          ∀ n : Nat, n + 0 = n
        """
        ctx = context.strip()
        header = textwrap.dedent(
            """
            -- Auto-generated by GameForge Lean4Verifier
            -- Mathematical certainty obligation
            """
        ).strip()
        body = textwrap.dedent(
            f"""
            {header}

            {ctx}

            theorem gameforge_goal : {statement} := by
              sorry
            """
        ).strip()
        return body + "\n"

    def create_obligation(self, statement: str, context: str = "") -> ProofObligation:
        oid = str(uuid.uuid4())[:12]
        src = self._skeleton(statement, context)
        obl = ProofObligation(
            obligation_id=oid,
            statement=statement,
            context=context,
            lean_source=src,
            status="pending",
        )
        self.obligations[oid] = obl
        path = self.work / f"{oid}.lean"
        path.write_text(src)
        self.log.add("obligation_created", id=oid, statement=statement[:200], path=str(path))
        return obl

    def attempt_proof(self, obligation_id: str, *, timeout_s: float = 30.0, replace_sorry_with: Optional[str] = None) -> ProofObligation:
        obl = self.obligations.get(obligation_id)
        if not obl:
            raise KeyError(obligation_id)

        path = self.work / f"{obligation_id}.lean"
        if replace_sorry_with:
            src = obl.lean_source.replace("sorry", replace_sorry_with.strip())
            path.write_text(src)
            obl.lean_source = src
            self.log.add("proof_tactic_injected", id=obligation_id, tactic=replace_sorry_with[:120])

        if not self.lean_bin:
            obl.status = "unavailable"
            obl.result_message = "lean binary not found; obligation recorded for offline proof"
            obl.finished_at = datetime.utcnow().isoformat()
            self.log.add("proof_unavailable", id=obligation_id)
            return obl

        try:
            proc = subprocess.run(
                [self.lean_bin, str(path)],
                capture_output=True,
                text=True,
                timeout=timeout_s,
                cwd=str(self.work),
            )
            out = (proc.stdout or "") + (proc.stderr or "")
            obl.finished_at = datetime.utcnow().isoformat()
            if proc.returncode == 0 and "sorry" not in obl.lean_source:
                obl.status = "proved"
                obl.result_message = out[-2000:] or "proved"
            elif "sorry" in obl.lean_source and proc.returncode == 0:
                obl.status = "sorry"
                obl.result_message = "file typechecks but goal closed with sorry — not a completed proof"
            else:
                obl.status = "failed"
                obl.result_message = out[-2000:]
            self.log.add(
                "proof_attempt",
                id=obligation_id,
                status=obl.status,
                returncode=proc.returncode,
            )
        except subprocess.TimeoutExpired:
            obl.status = "failed"
            obl.result_message = f"timeout after {timeout_s}s"
            obl.finished_at = datetime.utcnow().isoformat()
            self.log.add("proof_timeout", id=obligation_id)
        except Exception as e:
            obl.status = "failed"
            obl.result_message = str(e)
            obl.finished_at = datetime.utcnow().isoformat()
            self.log.add("proof_error", id=obligation_id, error=str(e))
        return obl

    def prove(self, statement: str, context: str = "", tactic: Optional[str] = None) -> Dict[str, Any]:
        """
        Create obligation and attempt verification.
        For certainty: status must be 'proved' (not sorry).
        """
        obl = self.create_obligation(statement, context)
        if tactic:
            # e.g. tactic = "rfl" or "simp" or multi-line tactics
            obl = self.attempt_proof(obl.obligation_id, replace_sorry_with=tactic)
        else:
            obl = self.attempt_proof(obl.obligation_id)
        return {
            "ok": obl.status == "proved",
            "certainty": obl.status == "proved",
            "obligation": obl.to_dict(),
            "lean_available": self.available,
            "log_tail": self.log.tail(5),
        }

    def status(self) -> Dict[str, Any]:
        by = {}
        for o in self.obligations.values():
            by[o.status] = by.get(o.status, 0) + 1
        return {
            "lean_available": self.available,
            "lean_bin": self.lean_bin,
            "work": str(self.work),
            "obligations": len(self.obligations),
            "by_status": by,
            "log_tail": self.log.tail(10),
        }


