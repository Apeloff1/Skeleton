    books = []
    chapter_templates = [
        ("Foundations","Core concepts and fundamentals.",["Key Principles","Core Terminology","Historical Context","Why It Matters","Getting Started"],["Define core concepts","Trace evolution","Set up environment"]),
        ("Core Techniques","Essential methods and approaches.",["Technique A","Technique B","Technique C","Choosing the Right Approach","Trade-off Analysis"],["Apply each technique","Benchmark approaches","Write comparison report"]),
        ("Intermediate Mastery","Building deeper understanding.",["Advanced Patterns","Common Pitfalls","Industry Best Practices","Real-World Case Studies"],["Identify anti-patterns","Apply best practices","Study real implementations"]),
        ("Advanced Topics","Expert-level deep dives.",["Edge Cases","Performance Optimization","Security Considerations","Scalability Patterns"],["Handle edge cases","Profile and optimize","Security audit"]),
        ("Practical Projects","Hands-on application.",["Project Architecture","Implementation","Testing Strategy","Deployment"],["Build end-to-end project","Write comprehensive tests","Deploy to production"]),
        ("Mastery & Beyond","Achieving true expertise.",["Contributing to Open Source","Teaching & Mentoring","Staying Current","Building Your Brand"],["Contribute to a project","Write a tutorial","Build portfolio piece"]),
    ]

    for cat, book_list in _EXTRA_BOOKS.items():
        for title, author, diff, hours in book_list:
            bid = _bid(title)
            modules = []
            for i, (ch_name, ch_desc, concepts, exercises) in enumerate(chapter_templates):
                ch_id = f"{bid}_ch{i+1:02d}"
                lessons = [{"id": f"{ch_id}_intro", "title": f"Chapter {i+1}: {ch_name}", "type": "reading", "content": f"{ch_desc} Applied to '{title}' by {author}.", "estimated_minutes": random.randint(20, 40)}]
                for j, concept in enumerate(concepts):
                    lessons.append({"id": f"{ch_id}_c{j+1}", "title": concept, "type": "deep_dive", "content": f"Deep study of {concept} as presented in '{title}'.", "estimated_minutes": random.randint(15, 45)})
                for j, ex in enumerate(exercises):
                    lessons.append({"id": f"{ch_id}_ex{j+1}", "title": f"Exercise: {ex}", "type": "exercise", "content": f"Practice: {ex}", "estimated_minutes": random.randint(15, 30)})
                modules.append({"id": ch_id, "name": ch_name, "summary": ch_desc, "lessons": lessons, "total_lessons": len(lessons)})
            books.append({
                "id": bid, "title": title, "author": author, "category": cat, "difficulty": diff,
                "chapters": modules, "total_chapters": len(modules),
                "total_lessons": sum(m["total_lessons"] for m in modules),
                "estimated_hours": hours,
                "description": f"Complete study of '{title}' by {author}. {len(modules)} chapters with deep-dives and exercises.",
            })
    return books


